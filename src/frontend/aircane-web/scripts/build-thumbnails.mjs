// Builds document thumbnails: art-source/document-thumbnails/*.png -> public/assets/document-thumbnails/*.webp,
// then regenerates src/features/library/thumbnails/manifest.generated.ts from the WebPs + thumbnails.meta.json.
// Node only (no shell commands) so it runs the same on Windows PowerShell, bash and CI.
// Usage: npm run thumbnails:build [-- --force]
import { existsSync } from 'node:fs'
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import sharp from 'sharp'

// One-shot tool: don't let sharp keep file handles open (breaks deleting files on Windows).
sharp.cache(false)

const here = path.dirname(fileURLToPath(import.meta.url))
const webRoot = path.resolve(here, '..')

export const defaultPaths = {
  sourceDir: path.resolve(webRoot, '../../../art-source/document-thumbnails'),
  metaFile: path.resolve(webRoot, '../../../art-source/document-thumbnails/thumbnails.meta.json'),
  outDir: path.resolve(webRoot, 'public/assets/document-thumbnails'),
  manifestFile: path.resolve(webRoot, 'src/features/library/thumbnails/manifest.generated.ts'),
}

export const TARGET_WIDTH = 320
export const WEBP_QUALITY = 80
const ASPECT = 3 / 4
const ASPECT_TOLERANCE = 0.04

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`

async function listFiles(dir, ext) {
  if (!existsSync(dir)) return []
  return (await readdir(dir)).filter((f) => f.toLowerCase().endsWith(ext)).sort()
}

async function convertAll({ sourceDir, outDir }, { force, log, warn }) {
  const pngs = await listFiles(sourceDir, '.png')
  const result = { converted: [], skipped: [], flagged: [] }
  if (pngs.length === 0) {
    log(`No PNG originals in ${sourceDir}; skipping conversion (using the committed WebPs).`)
    return result
  }
  await mkdir(outDir, { recursive: true })
  for (const file of pngs) {
    const stem = path.basename(file, path.extname(file))
    const src = path.join(sourceDir, file)
    const out = path.join(outDir, `${stem}.webp`)
    const meta = await sharp(src).metadata()
    const ratio = meta.width / meta.height
    if (Math.abs(ratio - ASPECT) / ASPECT > ASPECT_TOLERANCE) {
      warn(`${file}: ${meta.width}x${meta.height} (ratio ${ratio.toFixed(3)}) is not within ${ASPECT_TOLERANCE * 100}% of 3:4. Converted without cropping.`)
      result.flagged.push(stem)
    }
    if (!force && existsSync(out) && (await stat(out)).mtimeMs >= (await stat(src)).mtimeMs) {
      result.skipped.push(stem)
      continue
    }
    await sharp(src)
      .resize({ width: TARGET_WIDTH, withoutEnlargement: true })
      .webp({ quality: WEBP_QUALITY })
      .toFile(out)
    const before = (await stat(src)).size
    const after = (await stat(out)).size
    log(`converted ${file}: ${kb(before)} -> ${kb(after)}`)
    result.converted.push(stem)
  }
  log(`${result.converted.length} converted, ${result.skipped.length} up to date.`)
  return result
}

async function readMeta(metaFile) {
  if (!existsSync(metaFile)) return {}
  return JSON.parse(await readFile(metaFile, 'utf8'))
}

const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

function render(entries) {
  const items = entries
    .map(
      (e) =>
        `  { key: ${quote(e.key)}, file: ${quote(e.file)}, label: ${quote(e.label)}, tags: [${e.tags.map(quote).join(', ')}], width: ${e.width}, height: ${e.height} },`,
    )
    .join('\n')
  return `// GENERATED by scripts/build-thumbnails.mjs (npm run thumbnails:build). Do not edit by hand.
// Sources: public/assets/document-thumbnails/*.webp + art-source/document-thumbnails/thumbnails.meta.json

export interface ThumbnailEntry {
  /** File stem, e.g. "fantasy-knight-pf". */
  key: string
  /** File name inside /assets/document-thumbnails/. */
  file: string
  label: string
  tags: string[]
  width: number
  height: number
}

export const THUMBNAIL_MANIFEST: readonly ThumbnailEntry[] = [
${items}
]
`
}

async function buildManifest({ outDir, metaFile, manifestFile }, { log, warn }) {
  const meta = await readMeta(metaFile)
  const webps = await listFiles(outDir, '.webp')
  const entries = []
  for (const file of webps) {
    const key = path.basename(file, '.webp')
    const info = await sharp(path.join(outDir, file)).metadata()
    const m = meta[key]
    if (!m) warn(`${file} has no entry in thumbnails.meta.json; using label "${key}" and tag "uncategorized".`)
    entries.push({
      key,
      file,
      label: m?.label ?? key,
      tags: m?.tags ?? ['uncategorized'],
      width: info.width,
      height: info.height,
    })
  }
  for (const key of Object.keys(meta)) {
    if (!webps.includes(`${key}.webp`)) {
      warn(`thumbnails.meta.json has "${key}" but public/assets/document-thumbnails/${key}.webp does not exist.`)
    }
  }
  const next = render(entries)
  const prev = existsSync(manifestFile) ? await readFile(manifestFile, 'utf8') : null
  if (prev === next) {
    log(`Manifest up to date (${entries.length} thumbnails).`)
  } else {
    await mkdir(path.dirname(manifestFile), { recursive: true })
    await writeFile(manifestFile, next)
    log(`Manifest written (${entries.length} thumbnails).`)
  }
  return { entries, changed: prev !== next }
}

export async function run(paths = defaultPaths, opts = {}) {
  const ctx = { force: false, log: console.log, warn: (m) => console.warn(`WARN ${m}`), ...opts }
  const conversion = await convertAll(paths, ctx)
  const manifest = await buildManifest(paths, ctx)
  return { conversion, manifest }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  run(defaultPaths, { force: process.argv.includes('--force') }).catch((err) => {
    console.error(err)
    process.exit(1)
  })
}
